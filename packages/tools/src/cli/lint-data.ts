/** `npm run lint:data` - validate all data files (factions + fixtures) and report problems. `-- --table` also writes
 *  the low-confidence entries awaiting review (factions and core, not the fixture) to docs/research/low-confidence.md. */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { formatErrors, lintDataSet } from "@tcs/data";
import { readDataFiles } from "../data-files";

const files = readDataFiles(["core", "factions", "fixtures"]);
const { data, errors } = lintDataSet(files);
const errs = errors.filter((e) => e.severity === "error");
const warns = errors.filter((e) => e.severity === "warning");
console.log(`Data lint: ${Object.keys(files).length} files, ${Object.keys(data?.factions ?? {}).length} faction packs.`);
if (warns.length) console.log(`\n${warns.length} warning(s) (confidence 'low' entries awaiting review are listed here):\n${formatErrors(warns)}`);
if (process.argv.includes("--table")) {
  const low = warns.filter((w) => /confidence is low/.test(w.message) && !w.file.startsWith("fixtures/"));
  const byFile = new Map<string, string[]>();
  for (const w of low) { const l = byFile.get(w.file) ?? []; l.push(w.path); byFile.set(w.file, l); }
  const files = [...byFile.keys()].sort();
  const md = [
    "# Low-confidence data awaiting review",
    "",
    `Generated by \`npm run lint:data -- --table\` (${low.length} entries in ${files.length} files; the fixture faction is left out). Every value`,
    "here is a game value or comes from search extracts only (web pages cannot be opened from the container). The",
    "owner reviews them by area; raising one needs a public source (`add-data-entry` skill).",
    "",
    "| file | entries | which |",
    "|---|---:|---|",
    ...files.map((f) => { const l = byFile.get(f)!; return `| ${f} | ${l.length} | ${l.join(", ")} |`; }),
    "",
  ].join("\n");
  writeFileSync(fileURLToPath(new URL("../../../../docs/research/low-confidence.md", import.meta.url)), md);
  console.log(`\nWrote docs/research/low-confidence.md (${low.length} entries).`);
}
if (errs.length) {
  console.error(`\n${errs.length} error(s):\n${formatErrors(errs)}`);
  process.exit(1);
}
console.log("\nNo errors.");
